import { openCollection } from './helpers';
import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { unzipSync } from 'fflate';

test('portfolio drafts, visual designs, custom themes and external destinations survive reload and export', async ({ page, context }) => {
  test.setTimeout(90_000);
  await page.setViewportSize({ width: 1600, height: 1100 });
  await context.route('https://portfolio-example.test/**', route => route.fulfill({ status: 200, contentType: 'text/html', body: '<h1>Independent project destination</h1>' }));
  await page.goto('/#/new');
  await page.getByRole('button', { name: /Personal portfolio/ }).click();
  await openCollection(page, 'Portfolio content');
  const content = page.getByRole('dialog', { name: 'Portfolio content' });
  await content.getByRole('button', { name: 'New portfolio project', exact: true }).click();
  await content.getByLabel('Project title', { exact: true }).fill('Fieldnotes');
  await content.getByLabel('Website link', { exact: true }).fill('https://portfolio-example.test/live-work');
  await content.getByLabel('Category', { exact: true }).fill('Editorial design');
  await content.getByLabel('Summary', { exact: true }).fill('A publication for curious people.');
  await content.getByRole('button', { name: 'Save draft', exact: true }).click();
  await content.getByRole('button', { name: 'Close Portfolio content' }).click();
  await page.reload();
  await page.getByRole('button', { name: /^Preview/ }).click();
  const preview = page.frameLocator('iframe[title="Website preview"]');
  await expect(preview.getByText('No projects have been published yet.')).toBeVisible();
  await page.getByRole('button', { name: /Back to editor/ }).click();
  await openCollection(page, 'Portfolio content');
  await expect(content.getByLabel('Website link', { exact: true })).toHaveValue('https://portfolio-example.test/live-work');
  await content.getByRole('button', { name: 'Publish for export', exact: true }).click();
  await content.getByLabel('Project title', { exact: true }).fill('Private rewrite');
  await content.getByRole('button', { name: 'Save draft', exact: true }).click();
  await content.getByRole('button', { name: 'Close Portfolio content' }).click();

  await page.getByRole('button', { name: 'Site theme', exact: true }).click();
  const theme = page.getByRole('dialog', { name: 'Site theme' });
  await theme.getByRole('radio', { name: 'Ink', exact: true }).check();
  await theme.getByLabel('Accent color', { exact: true }).fill('#ddbb99');
  await theme.getByRole('radio', { name: 'Classic serif', exact: true }).check();
  expect(await theme.locator('.theme-sample > p').nth(1).evaluate(element => getComputedStyle(element).color)).toBe('rgb(185, 186, 181)');
  expect(await theme.getByLabel('Accent color', { exact: true }).evaluate(element => element.getBoundingClientRect().width)).toBe(28);
  await theme.screenshot({ path: '.artifacts/portfolio-theme-picker.png' });
  await theme.getByRole('button', { name: 'Apply theme' }).click();
  const canvas = page.frameLocator('iframe');
  await canvas.getByRole('heading', { name: 'Selected work', exact: true }).click();
  await expect(page.getByRole('radio', { name: /portfolio design$/ })).toHaveCount(6);
  await page.getByRole('radio', { name: 'Gallery portfolio design', exact: true }).focus();
  await page.getByRole('radio', { name: 'Gallery portfolio design', exact: true }).press('ArrowDown');
  await expect(page.getByRole('radio', { name: 'Editorial portfolio design', exact: true })).toBeChecked();
  await page.getByRole('radio', { name: 'Poster portfolio design', exact: true }).check();
  await page.getByRole('radio', { name: 'Entrance reveal', exact: true }).focus();
  await page.getByRole('radio', { name: 'Entrance reveal', exact: true }).press('Space');
  await page.screenshot({ path: '.artifacts/portfolio-design-editor.png', fullPage: true });
  await expect(page.getByRole('status').filter({ hasText: 'Saved on this device' })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: /^Preview/ }).click();
  await expect(preview.locator('.portfolio-collection')).toHaveAttribute('data-design', 'poster');
  await expect(preview.locator('.portfolio-collection')).toHaveAttribute('data-motion', 'reveal');
  await expect(preview.getByRole('heading', { name: 'Fieldnotes', exact: true })).toBeVisible();
  await expect(preview.getByText('Private rewrite')).toHaveCount(0);
  expect(await preview.locator('.site').evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(25, 27, 28)');
  expect(await preview.locator('.site').evaluate(element => getComputedStyle(element).getPropertyValue('--accent').trim())).toBe('#ddbb99');
  await expect(preview.locator('.site')).toHaveAttribute('data-font', 'serif');
  for (const width of [390, 768, 1280]) {
    await page.getByRole('combobox', { name: 'Width', exact: true }).selectOption(String(width));
    expect(await preview.locator('body').evaluate(element => element.scrollWidth <= element.ownerDocument.documentElement.clientWidth)).toBe(true);
  }
  await page.locator('iframe').screenshot({ path: '.artifacts/portfolio-linked-preview.png' });
  const link = preview.getByRole('link', { name: 'Visit Fieldnotes website (opens in a new tab)', exact: true });
  await expect(link).toHaveAttribute('href', 'https://portfolio-example.test/live-work');
  await expect(link).toHaveAttribute('rel', 'noopener noreferrer');
  const popupPromise = context.waitForEvent('page');
  await link.click();
  const popup = await popupPromise;
  await expect(popup.getByRole('heading', { name: 'Independent project destination' })).toBeVisible();
  expect(popup.url()).toBe('https://portfolio-example.test/live-work');
  await popup.close();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  expect(await preview.locator('.portfolio-card').evaluate(element => getComputedStyle(element).animationName)).toBe('none');
  await page.getByRole('button', { name: /Back to editor/ }).click();
  await page.getByRole('button', { name: /^Download code/ }).click();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download ZIP', exact: true }).click();
  const zip = unzipSync(await readFile((await (await pending).path())!));
  expect(zip['app/api/admin/portfolio/route.ts']).toBeDefined();
  expect(zip['app/portfolio/[slug]/page.tsx']).toBeUndefined();
  const project = JSON.parse(new TextDecoder().decode(zip['project.apl.json'])).website;
  expect(project.theme.accent).toBe('#ddbb99');
  expect(project.content.portfolio[0].draft.title).toBe('Private rewrite');
  expect(project.content.portfolio[0].published.title).toBe('Fieldnotes');
  expect(project.pages[0].nodes.find((node: { type: string }) => node.type === 'PortfolioCollection').props.design).toBe('poster');
  expect(new TextDecoder().decode(zip['site-data.json'])).not.toContain('Private rewrite');
});
