import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { unzipSync } from 'fflate';

test('compose, style, undo, reload and export a responsive nested layout', async ({ page }) => {
  test.setTimeout(90_000);
  await page.setViewportSize({ width: 1600, height: 1100 });
  await page.goto('/#/new');
  await page.getByRole('button', { name: /Business \/ studio/ }).click();
  await page.getByRole('button', { name: 'Add layout', exact: true }).click();
  const frame = page.frameLocator('iframe');
  await frame.getByRole('heading', { name: 'Make room for a good idea.' }).click();
  await page.getByRole('textbox', { name: 'Heading text', exact: true }).fill('A layout of our own');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(frame.getByRole('heading', { name: 'Make room for a good idea.' })).toBeVisible();
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await frame.getByRole('heading', { name: 'A layout of our own' }).click();
  await page.getByRole('button', { name: 'Column', exact: true }).last().click();
  await page.getByRole('spinbutton', { name: 'mobile element gap', exact: true }).fill('16');
  await page.getByRole('button', { name: 'Column group', exact: true }).last().click();
  await page.getByRole('combobox', { name: 'desktop column widths', exact: true }).selectOption('two-one');
  await page.getByRole('spinbutton', { name: 'mobile column gap', exact: true }).fill('12');
  await page.getByRole('spinbutton', { name: 'tablet column gap', exact: true }).fill('20');
  await page.getByRole('spinbutton', { name: 'desktop column gap', exact: true }).fill('');
  await expect(page.getByText('Inherits 20px', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Layout section', exact: true }).last().click();
  await page.getByRole('spinbutton', { name: 'mobile section padding', exact: true }).fill('24');
  await page.getByRole('spinbutton', { name: 'tablet section padding', exact: true }).fill('40');
  await page.getByRole('spinbutton', { name: 'desktop section padding', exact: true }).fill('64');
  await page.getByRole('list').getByText('Outline', { exact: true }).click();
  await page.getByRole('button', { name: 'Select Button: Explore our work', exact: true }).click();
  await page.getByRole('textbox', { name: 'Button label', exact: true }).fill('Contact our studio');
  await page.getByRole('combobox', { name: 'Button destination', exact: true }).selectOption({ label: 'Home · contact' });
  await page.getByRole('radio', { name: 'Outline button design', exact: true }).focus();
  await page.getByRole('radio', { name: 'Outline button design', exact: true }).press('Space');
  await page.getByRole('radio', { name: 'Moving arrow', exact: true }).focus();
  await page.getByRole('radio', { name: 'Moving arrow', exact: true }).press('Space');
  await expect(page.getByRole('radio', { name: 'Moving arrow', exact: true })).toBeChecked();
  await expect(page.getByRole('status').filter({ hasText: 'Saved on this device' })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: /^Preview/ }).click();
  const preview = page.frameLocator('iframe[title="Website preview"]');
  await expect(preview.getByRole('heading', { name: 'A layout of our own' })).toBeVisible();
  const button = preview.getByRole('link', { name: 'Contact our studio' });
  await expect(button).toHaveAttribute('data-design', 'outline');
  await expect(button).toHaveAttribute('data-motion', 'arrow');
  for (const [width, count, gap, pad] of [[390, 1, 12, 24], [768, 2, 20, 40], [1280, 2, 20, 64]]) {
    await page.getByRole('combobox', { name: 'Width', exact: true }).selectOption(String(width));
    const metrics = await preview.locator('.apl-column-grid').evaluate(element => ({ tracks: getComputedStyle(element).gridTemplateColumns.split(' ').map(parseFloat), gap: parseFloat(getComputedStyle(element).gap) }));
    expect(metrics.tracks).toHaveLength(count); expect(metrics.gap).toBe(gap);
    if (width === 1280) expect(metrics.tracks[0] / metrics.tracks[1]).toBeCloseTo(2, 1);
    expect(await preview.locator('.apl-section').evaluate(element => parseFloat(getComputedStyle(element).paddingTop))).toBe(pad);
    expect(await preview.locator('body').evaluate(element => element.scrollWidth <= element.ownerDocument.documentElement.clientWidth)).toBe(true);
    await expect(preview.locator('.apl-column')).toHaveCount(2);
  }
  await button.click(); await expect(preview.locator('#contact')).toBeInViewport();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await button.hover();
  expect(await button.locator('.apl-button-arrow').evaluate(element => getComputedStyle(element).transform)).toBe('none');
  await page.getByRole('button', { name: /Back to editor/ }).click();
  await page.getByRole('button', { name: /^Download code/ }).click();
  const pending = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download ZIP', exact: true }).click();
  const zip = unzipSync(await readFile((await (await pending).path())!));
  expect(zip['src/site/Columns.tsx']).toBeDefined(); expect(zip['src/site/Button.tsx']).toBeDefined();
  const saved = JSON.parse(new TextDecoder().decode(zip['project.apl.json'])).website;
  const section = saved.pages[0].nodes.find((node: { type: string }) => node.type === 'Section');
  expect(section.children[0].props.layout.desktop).toBe('two-one');
  expect(section.children[0].props.gap).toEqual({ mobile: 12, tablet: 20 });
  expect(section.children[0].children[0].children[0].props.text).toBe('A layout of our own');
});

test('page tree adds and reorders nested content with keyboard-accessible controls', async ({ page }) => {
  test.setTimeout(60_000);
  await page.setViewportSize({ width: 1600, height: 1100 });
  await page.goto('/#/new'); await page.getByRole('button', { name: /Business \/ studio/ }).click();
  await page.getByRole('button', { name: 'Add layout', exact: true }).click();
  await page.getByRole('list').getByText('Outline', { exact: true }).click();
  const tree = page.getByRole('region', { name: 'Page structure', exact: true });
  await expect(tree).not.toContainText('default-zone');
  await tree.getByRole('button', { name: 'Move Column 1 down', exact: true }).click();
  const frame = page.frameLocator('iframe');
  await expect(frame.locator('.apl-column').first().locator('.apl-image')).toHaveCount(1);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(frame.locator('.apl-column').first().locator('.apl-heading')).toHaveCount(1);
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(frame.locator('.apl-column').first().locator('.apl-image')).toHaveCount(1);
  await page.getByRole('list').getByText('Outline', { exact: true }).click();
  await tree.getByRole('combobox', { name: 'Element to add to Column 2', exact: true }).selectOption('Heading');
  await tree.getByRole('button', { name: 'Add Heading to Column 2', exact: true }).click();
  await page.getByRole('textbox', { name: 'Heading text', exact: true }).fill('Another idea');
  await tree.getByRole('button', { name: 'Move Heading: Another idea up', exact: true }).click();
  await expect(frame.locator('.apl-column').nth(1).locator('.apl-heading')).toHaveCount(2);
  await tree.getByRole('button', { name: 'Add column', exact: true }).click();
  await tree.getByRole('button', { name: 'Add column', exact: true }).click();
  await expect(tree.getByRole('button', { name: 'Add column', exact: true })).toBeDisabled();
  await expect(frame.locator('.apl-column')).toHaveCount(4);
  await tree.getByRole('button', { name: 'Select Column group', exact: true }).click();
  await page.getByRole('combobox', { name: 'desktop column widths', exact: true }).selectOption('quarters');
  await expect(page.getByRole('status').filter({ hasText: 'Saved on this device' })).toBeVisible();
  await page.reload(); await page.getByRole('button', { name: /^Preview/ }).click();
  const preview = page.frameLocator('iframe[title="Website preview"]');
  await expect(preview.locator('.apl-column')).toHaveCount(4);
  await expect(preview.locator('.apl-column').first().locator('.apl-image')).toHaveCount(1);
  expect(await preview.locator('.apl-column-grid').evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)).toBe(4);
  const order = await preview.locator('.apl-column').nth(1).locator('[data-layout-node]').evaluateAll(elements => elements.map(element => element.textContent?.trim()));
  expect(order.indexOf('Another idea')).toBeLessThan(order.indexOf('Explore our work'));
  await page.getByRole('combobox', { name: 'Width', exact: true }).selectOption('390');
  expect(await preview.locator('.apl-column-grid').evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)).toBe(1);
});
