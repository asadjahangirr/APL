import { openCollection } from './helpers';
import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { unzipSync } from 'fflate';

test('article draft, publication, responsive preview and independent download', async ({ page }) => {
  test.setTimeout(90_000);
  await page.setViewportSize({ width: 1500, height: 1000 });
  await page.goto('/#/new');
  await page.getByRole('button', { name: /Business \/ studio/ }).click();
  await page.frameLocator('iframe').getByRole('heading', { name: 'A little clarity goes a long way.' }).click();
  await expect(page.getByRole('radio', { name: /services design$/ })).toHaveCount(3);
  await page.getByRole('radio', { name: 'Numbered rows services design' }).check();
  await openCollection(page, 'Articles content');
  const dialog = page.getByRole('dialog', { name: 'Articles content' });
  await dialog.getByRole('button', { name: 'Add articles collection to this page' }).click();
  await dialog.getByRole('button', { name: 'New article', exact: true }).click();
  await dialog.getByLabel('Title', { exact: true }).fill('The shape of a good idea');
  await dialog.getByLabel('URL slug').fill('good-idea');
  await dialog.getByLabel('Summary', { exact: true }).fill('Thoughts on better creative work.');
  await dialog.getByLabel('Body', { exact: true }).fill('First paragraph.\n\nSecond paragraph.');
  await dialog.getByRole('button', { name: 'Save draft', exact: true }).click();
  await dialog.getByRole('button', { name: 'Close Articles content' }).click();
  await page.reload();
  await page.getByRole('button', { name: /^Preview/ }).click();
  const preview = page.frameLocator('iframe[title="Website preview"]');
  await expect(preview.locator('.static-services')).toHaveAttribute('data-design', 'numbered');
  await page.getByLabel('Preview page').selectOption('articles-cms');
  await expect(preview.getByText('No articles have been published yet.')).toBeVisible();
  await page.getByRole('button', { name: /Back to editor/ }).click();
  await openCollection(page, 'Articles content');
  await dialog.getByRole('button', { name: 'Publish for export', exact: true }).click();
  await dialog.getByLabel('Title', { exact: true }).fill('A private rewrite');
  await dialog.getByRole('button', { name: 'Save draft', exact: true }).click();
  await dialog.getByRole('button', { name: 'Close Articles content' }).click();
  await page.getByRole('button', { name: 'Site header & footer', exact: true }).click();
  const shared = page.getByRole('dialog', { name: 'Site header & footer' });
  await expect(shared).toBeVisible({ timeout: 15_000 });
  await expect(shared.getByRole('radio', { name: /footer design$/ })).toHaveCount(4);
  await shared.getByRole('radio', { name: 'Editorial footer design' }).check();
  await shared.getByRole('button', { name: 'Save shared settings' }).click();
  await page.getByRole('button', { name: /^Preview/ }).click();
  await page.getByLabel('Preview page').selectOption('articles-cms');
  await expect(preview.locator('.site-footer')).toHaveAttribute('data-design', 'editorial');
  await expect(preview.getByRole('heading', { name: 'The shape of a good idea' })).toBeVisible();
  await expect(preview.getByText('A private rewrite')).toHaveCount(0);
  await page.locator('iframe[title="Website preview"]').screenshot({ path: '.artifacts/articles-list-preview.png' });
  await preview.getByRole('link', { name: 'The shape of a good idea', exact: true }).click();
  await expect(preview.getByRole('heading', { level: 1, name: 'The shape of a good idea' })).toBeVisible();
  await expect(preview.getByText('Second paragraph.')).toBeVisible();
  await page.locator('iframe[title="Website preview"]').screenshot({ path: '.artifacts/articles-detail-preview.png' });
  for (const width of [390, 768, 1280]) {
    await page.getByLabel('Width').selectOption(String(width));
    expect(await preview.locator('body').evaluate(element => element.scrollWidth <= element.ownerDocument.documentElement.clientWidth)).toBe(true);
  }
  await page.getByRole('button', { name: /Back to editor/ }).click();
  await page.getByRole('button', { name: /^Download code/ }).click();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download ZIP' }).click();
  const zip = unzipSync(await readFile((await (await pending).path())!));
  expect(zip['app/articles/[slug]/page.tsx']).toBeDefined();
  expect(zip['app/api/admin/articles/route.ts']).toBeDefined();
  expect(zip['lib/services.ts']).toBeUndefined();
  const project = JSON.parse(new TextDecoder().decode(zip['project.apl.json'])).website;
  expect(project.content.articles[0].draft.title).toBe('A private rewrite');
  expect(project.content.articles[0].published.title).toBe('The shape of a good idea');
  expect(project.shared.footer.props.design).toBe('editorial');
});
