import { openCollection } from './helpers';
import {test,expect} from '@playwright/test';
test('services keep drafts separate through reload, preview, publication and export',async({page})=>{
  // Includes recovery after reload, responsive previews and a generated ZIP.
  test.setTimeout(60_000);
  await page.goto('/#/new');await page.getByRole('button',{name:/Business \/ studio/}).click();
  await openCollection(page, 'Services content');
  const dialog=page.getByRole('dialog',{name:'Services content'});
  await dialog.getByRole('button',{name:'Add services collection to this page'}).click();
  await dialog.getByRole('button',{name:'New service',exact:true}).click();
  await dialog.getByLabel('Title',{exact:true}).fill('Brand strategy');
  await dialog.getByLabel('URL slug').fill('brand-strategy');
  await dialog.getByLabel('Summary',{exact:true}).fill('A clear direction for your business.');
  await dialog.getByLabel('Body',{exact:true}).fill('Start with a shared understanding.');
  await dialog.getByRole('button',{name:'Save draft',exact:true}).click();
  await dialog.getByRole('button',{name:'Close Services content'}).click();
  await page.reload();await page.getByRole('button',{name:/^Preview/}).click();
  await page.getByLabel('Preview page').selectOption('services-cms');
  const frame=page.frameLocator('iframe');
  await expect(frame.getByText('No services have been published yet.')).toBeVisible();
  await page.getByRole('button',{name:/Back to editor/}).click();
  await openCollection(page, 'Services content');
  await expect(dialog.getByLabel('Summary',{exact:true})).toHaveValue('A clear direction for your business.');
  await expect(dialog.getByLabel('Body',{exact:true})).toHaveValue('Start with a shared understanding.');
  await dialog.getByRole('button',{name:'Publish for export',exact:true}).click();
  await dialog.getByLabel('Title',{exact:true}).fill('Private revised title');
  await dialog.getByRole('button',{name:'Save draft',exact:true}).click();
  await dialog.screenshot({path:'.artifacts/cms-content-editor.png'});
  await dialog.getByRole('button',{name:'Preview draft',exact:true}).click();
  await expect(dialog.getByRole('heading',{name:'Private revised title',exact:true})).toBeVisible();
  await dialog.getByRole('button',{name:'Close Services content'}).click();
  await page.getByRole('button',{name:/^Preview/}).click();
  await page.getByLabel('Preview page').selectOption('services-cms');
  await expect(frame.getByRole('heading',{name:'Brand strategy',exact:true})).toBeVisible();
  await expect(frame.getByText('Private revised title')).toHaveCount(0);
  await frame.getByRole('link',{name:'Brand strategy',exact:true}).click();
  await expect(frame.getByRole('heading',{level:1,name:'Brand strategy'})).toBeVisible();
  await page.locator('iframe').screenshot({path:'.artifacts/cms-service-preview.png'});
  await page.getByLabel('Width').selectOption('390');
  await expect(frame.getByText('Start with a shared understanding.')).toBeVisible();
  await page.getByRole('button',{name:/Back to editor/}).click();
  await page.getByRole('button',{name:/Download code/}).click();
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download ZIP',exact:true}).click();expect((await download).suggestedFilename()).toMatch(/\.zip$/);
});
